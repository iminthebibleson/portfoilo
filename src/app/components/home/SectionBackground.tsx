const SHAPE_NAMES = Object.keys(SHAPE_PATHS);

function ShapeGlyph({
  shapeName,
  className,
}: {
  shapeName: string;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      fill="currentColor"
      aria-hidden="true"
    >
      <path d={SHAPE_PATHS[shapeName]} />
    </svg>
  );
}

export default function SectionBackground({
  count = 8,
  sizeRange = [18, 42],
  colors = ["#ECE6F0", "#9C96A5", "#C6FF6B", "#CBB8FF", "#1B2A0E", "211A33"],
  className = "",
}: AndroidScatterProps) {
  const [shapes, setShapes] = useState<AndroidShapeConfig[]>([]);
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setShapes(generateShapes(count, sizeRange, colors));
    const raf = requestAnimationFrame(() => setMounted(true));
    return () => cancelAnimationFrame(raf);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);


  return (
    <div
      className={`pointer-events-none absolute inset-0 w-full overflow-hidden z-0 ${className}`}
      aria-hidden="true"
    >
      {shapes.map((shape) => (
        <div
          key={shape.id}
          style={{
            position: "absolute",
            top: `${shape.top}%`,
            left: `${shape.left}%`,
            width: shape.size,
            height: shape.size,
            opacity: mounted ? 0.6 : 0,
            transform: mounted ? "scale(1)" : "scale(0)",
            transition: `opacity ${shape.duration}ms ease-out ${shape.delay}ms, transform ${shape.duration}ms cubic-bezier(0.34, 1.56, 0.64, 1) ${shape.delay}ms`,
          }}
        >
          <div
            style={{
              width: "100%",
              height: "100%",
              color: shape.color,
              // @ts-expect-error
              "--start-rotate": `${shape.rotation}deg`,
              animation: mounted
                ? `${shape.spinDirection === 1 ? "spin-cw" : "spin-ccw"
                } ${shape.spinDuration}s linear infinite`
                : "none",
              transform: `rotate(${shape.rotation}deg)`,
            }}
          >
            <ShapeGlyph shapeName={shape.shapeName} className="h-full w-full" />
          </div>
        </div>
      ))}

      <style jsx>{`
        @keyframes spin-cw {
          from {
            transform: rotate(var(--start-rotate));
          }
          to {
            transform: rotate(calc(var(--start-rotate) + 360deg));
          }
        }
        @keyframes spin-ccw {
          from {
            transform: rotate(var(--start-rotate));
          }
          to {
            transform: rotate(calc(var(--start-rotate) - 360deg));
          }
        }
        @media (prefers-reduced-motion: reduce) {
          div {
            animation: none !important;
            transition: none !important;
          }
        }
      `}</style>
    </div>
  );
}